BEGIN;
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50)  NOT NULL UNIQUE,
    email           VARCHAR(255) NOT NULL UNIQUE,
    password_hash   TEXT         NOT NULL,
    role            VARCHAR(20)  NOT NULL DEFAULT 'user'
                    CHECK (role IN ('user', 'admin')),
    is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE TABLE documents (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title           VARCHAR(255) NOT NULL,
    description     TEXT,
    file_path       TEXT         NOT NULL,
    file_hash       VARCHAR(64)  NOT NULL CHECK (file_hash ~ '^[0-9a-fA-F]{64}$'),
    total_pages     INTEGER      CHECK (total_pages IS NULL OR total_pages >= 0),
    status          VARCHAR(20)  NOT NULL DEFAULT 'uploaded'
                    CHECK (status IN ('uploaded', 'processing', 'ready', 'failed')),
    visibility      VARCHAR(20)  NOT NULL DEFAULT 'private'
                    CHECK (visibility IN ('private', 'shared', 'public')),
    upload_date     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_documents_owner_file_hash UNIQUE (owner_id, file_hash)
);
CREATE TABLE chapters (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     BIGINT       NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    chapter_number  INTEGER      NOT NULL CHECK (chapter_number > 0),
    title           VARCHAR(500) NOT NULL,
    start_page      INTEGER      CHECK (start_page IS NULL OR start_page > 0),
    end_page        INTEGER      CHECK (end_page IS NULL OR end_page > 0),
    summary         TEXT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_chapters_document_number UNIQUE (document_id, chapter_number),
    CONSTRAINT uq_chapters_document_id UNIQUE (document_id, id),
    CONSTRAINT ck_chapters_page_range CHECK (
        start_page IS NULL OR end_page IS NULL OR end_page >= start_page
    )
);
CREATE TABLE document_chunks (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     BIGINT       NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    chapter_id      BIGINT,
    page_number     INTEGER      CHECK (page_number IS NULL OR page_number > 0),
    chunk_index     INTEGER      NOT NULL CHECK (chunk_index >= 0),
    content         TEXT         NOT NULL DEFAULT '',
    chroma_id       VARCHAR(255) UNIQUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_document_chunks_document_index UNIQUE (document_id, chunk_index),
    CONSTRAINT fk_document_chunks_chapter_same_document
        FOREIGN KEY (document_id, chapter_id)
        REFERENCES chapters(document_id, id)
);
CREATE TABLE conversations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    document_id     BIGINT       REFERENCES documents(id) ON DELETE CASCADE,
    chapter_id      BIGINT,
    title           VARCHAR(255) NOT NULL DEFAULT 'Cuộc trò chuyện mới',
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_conversations_chapter_same_document
        FOREIGN KEY (document_id, chapter_id)
        REFERENCES chapters(document_id, id),
    CONSTRAINT ck_conversations_chapter_requires_document
        CHECK (chapter_id IS NULL OR document_id IS NOT NULL)
);
CREATE TABLE chat_history (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id     BIGINT      NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    question            TEXT        NOT NULL,
    answer              TEXT        NOT NULL,
    retrieved_chunks    JSONB       NOT NULL DEFAULT '[]'::JSONB,
    citations           JSONB       NOT NULL DEFAULT '[]'::JSONB,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_chat_history_retrieved_chunks_array
        CHECK (JSONB_TYPEOF(retrieved_chunks) = 'array'),
    CONSTRAINT ck_chat_history_citations_json
        CHECK (JSONB_TYPEOF(citations) IN ('array', 'object'))
);
CREATE TABLE quizzes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     BIGINT       NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    chapter_id      BIGINT,
    title           VARCHAR(255) NOT NULL,
    question_count  INTEGER      NOT NULL DEFAULT 0 CHECK (question_count >= 0),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_quizzes_document_id UNIQUE (document_id, id),
    CONSTRAINT fk_quizzes_chapter_same_document
        FOREIGN KEY (document_id, chapter_id)
        REFERENCES chapters(document_id, id)
);
CREATE TABLE questions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id         BIGINT       NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
    question_text   TEXT         NOT NULL,
    question_type   VARCHAR(30)  NOT NULL
                    CHECK (question_type IN ('multiple_choice', 'multiple_select', 'true_false', 'short_answer')),
    option_a        TEXT,
    option_b        TEXT,
    option_c        TEXT,
    option_d        TEXT,
    correct_answer  TEXT         NOT NULL,
    explanation     TEXT,
    source_page     INTEGER      CHECK (source_page IS NULL OR source_page > 0),
    source_chunk_id BIGINT       REFERENCES document_chunks(id) ON DELETE SET NULL,
    CONSTRAINT uq_questions_quiz_id UNIQUE (quiz_id, id)
);
CREATE TABLE quiz_attempts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    quiz_id             BIGINT       NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
    score               NUMERIC(5,2) CHECK (score IS NULL OR score BETWEEN 0 AND 100),
    correct_count       INTEGER      NOT NULL DEFAULT 0 CHECK (correct_count >= 0),
    total_questions     INTEGER      NOT NULL DEFAULT 0 CHECK (total_questions >= 0),
    started_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    completed_at        TIMESTAMPTZ,
    CONSTRAINT ck_quiz_attempt_counts CHECK (correct_count <= total_questions),
    CONSTRAINT ck_quiz_attempt_time CHECK (completed_at IS NULL OR completed_at >= started_at),
    CONSTRAINT uq_quiz_attempts_id_quiz UNIQUE (id, quiz_id)
);
CREATE TABLE quiz_attempt_answers (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id          BIGINT       NOT NULL REFERENCES quiz_attempts(id) ON DELETE CASCADE,
    question_id         BIGINT       NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    selected_answer     JSONB,
    is_correct          BOOLEAN,
    answered_at         TIMESTAMPTZ,
    CONSTRAINT uq_attempt_question UNIQUE (attempt_id, question_id),
    CONSTRAINT ck_selected_answer_json CHECK (
        selected_answer IS NULL OR JSONB_TYPEOF(selected_answer) IN ('array', 'object', 'string', 'number', 'boolean')
    )
);
CREATE TABLE flashcards (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    document_id     BIGINT       NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    chapter_id      BIGINT,
    front           TEXT         NOT NULL,
    back            TEXT         NOT NULL,
    source_page     INTEGER      CHECK (source_page IS NULL OR source_page > 0),
    source_chunk_id BIGINT       REFERENCES document_chunks(id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_flashcards_chapter_same_document
        FOREIGN KEY (document_id, chapter_id)
        REFERENCES chapters(document_id, id)
);
CREATE TABLE study_sessions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    document_id         BIGINT       NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    title               VARCHAR(255),
    duration_minutes    INTEGER      NOT NULL DEFAULT 0 CHECK (duration_minutes >= 0),
    status              VARCHAR(20)  NOT NULL DEFAULT 'in_progress'
                        CHECK (status IN ('in_progress', 'completed', 'abandoned')),
    started_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    completed_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_study_sessions_time CHECK (completed_at IS NULL OR completed_at >= started_at)
);
CREATE TABLE study_session_items (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id          BIGINT       NOT NULL REFERENCES study_sessions(id) ON DELETE CASCADE,
    chapter_id          BIGINT       REFERENCES chapters(id) ON DELETE SET NULL,
    activity_type       VARCHAR(30)  NOT NULL
                        CHECK (activity_type IN ('reading', 'chat', 'quiz', 'flashcards', 'summary', 'other')),
    duration_minutes    INTEGER      NOT NULL DEFAULT 0 CHECK (duration_minutes >= 0),
    elapsed_minutes     INTEGER      NOT NULL DEFAULT 0 CHECK (elapsed_minutes >= 0),
    status              VARCHAR(20)  NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending', 'in_progress', 'completed', 'skipped'))
);
CREATE TABLE user_chapter_progress (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    chapter_id          BIGINT       NOT NULL REFERENCES chapters(id) ON DELETE CASCADE,
    progress_percent    NUMERIC(5,2) NOT NULL DEFAULT 0
                        CHECK (progress_percent BETWEEN 0 AND 100),
    time_spent_minutes  INTEGER      NOT NULL DEFAULT 0 CHECK (time_spent_minutes >= 0),
    status              VARCHAR(20)  NOT NULL DEFAULT 'not_started'
                        CHECK (status IN ('not_started', 'in_progress', 'completed')),
    last_studied_at     TIMESTAMPTZ,
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_user_chapter_progress UNIQUE (user_id, chapter_id)
);
CREATE INDEX idx_documents_owner_upload_date ON documents (owner_id, upload_date DESC);
CREATE INDEX idx_documents_visibility_status ON documents (visibility, status);
CREATE INDEX idx_chapters_document ON chapters (document_id, chapter_number);
CREATE INDEX idx_document_chunks_document_page ON document_chunks (document_id, page_number);
CREATE INDEX idx_document_chunks_chapter ON document_chunks (chapter_id);
CREATE INDEX idx_conversations_user_created ON conversations (user_id, created_at DESC);
CREATE INDEX idx_conversations_document ON conversations (document_id);
CREATE INDEX idx_chat_history_conversation_created ON chat_history (conversation_id, created_at);
CREATE INDEX idx_quizzes_document ON quizzes (document_id);
CREATE INDEX idx_quizzes_chapter ON quizzes (chapter_id);
CREATE INDEX idx_questions_quiz ON questions (quiz_id);
CREATE INDEX idx_questions_source_chunk ON questions (source_chunk_id);
CREATE INDEX idx_quiz_attempts_user_started ON quiz_attempts (user_id, started_at DESC);
CREATE INDEX idx_quiz_attempts_quiz ON quiz_attempts (quiz_id);
CREATE INDEX idx_quiz_attempt_answers_question ON quiz_attempt_answers (question_id);
CREATE INDEX idx_flashcards_user_document ON flashcards (user_id, document_id);
CREATE INDEX idx_flashcards_chapter ON flashcards (chapter_id);
CREATE INDEX idx_study_sessions_user_started ON study_sessions (user_id, started_at DESC);
CREATE INDEX idx_study_sessions_document ON study_sessions (document_id);
CREATE INDEX idx_study_session_items_session ON study_session_items (session_id);
CREATE INDEX idx_study_session_items_chapter ON study_session_items (chapter_id);
CREATE INDEX idx_user_chapter_progress_chapter ON user_chapter_progress (chapter_id);
CREATE FUNCTION set_updated_at_column()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_user_chapter_progress_updated_at
BEFORE UPDATE ON user_chapter_progress
FOR EACH ROW
EXECUTE FUNCTION set_updated_at_column();
COMMIT;
